// Primary-lane evidence projection. Never writes or mutates the simulator payload.
// Backend 1 machine-health identity: full original event ordinal, not filtered index.
const eventId = (sessionId, recordTick, ordinal) => 'je1_' +
  Buffer.from(JSON.stringify([sessionId, 'primary', recordTick, ordinal])).toString('base64url');
const tuple = e => `${e.machine}:${e.component}:${e.technician}:${e.kind}`;
const component = e => `${e.machine}:${e.component}`;
const matches = (action, e) => action?.some(a => a[0] === e.machine && a[1] === e.component && a[2] === e.technician);

function project(sessionId, payload, previous = null, command = null) {
  const records = payload.primary.records;
  const tick = payload.primary.state.tick;
  const p = previous ? structuredClone(previous) : {
    version: 1, processedThroughTick: records[0]?.tick ?? tick,
    historyCoverage: (records[0]?.tick ?? tick) === 0 ? 'COMPLETE' : 'PARTIAL',
    failures: {}, orders: {},
  };
  for (const record of records) {
    if (record.tick < p.processedThroughTick) continue;
    if (record.tick !== p.processedThroughTick) {
      if (previous) throw new Error('Work-order projection trace gap');
      p.historyCoverage = 'PARTIAL';
      p.failures = {}; // Missing intervals can contain consumption or a new failure.
    }
    record.events.forEach((e, ordinal) => {
      const id = eventId(sessionId, record.tick, ordinal);
      if (e.type === 'failure') p.failures[component(e)] = { id, tick: e.tick };
      if (e.type === 'start') {
        if (p.orders[id]) return;
        const failure = e.kind === 'CM' ? p.failures[component(e)] : null;
        const decision = payload.decisions?.find(d => d.tick === e.tick && matches(d.action, e));
        let assignmentSource = 'UNKNOWN';
        if (decision) assignmentSource = decision.actor === 'automatic' ? 'AUTOMATIC' : decision.override ? 'OVERRIDE' : 'MANUAL_APPROVAL';
        // Command evidence only applies to intervals newly generated by that command.
        if (command && record.tick >= command.fromTick) {
          assignmentSource = command.name === 'override' ? 'OVERRIDE'
            : command.name === 'approve' ? 'MANUAL_APPROVAL' : 'AUTOMATIC';
        }
        p.orders[id] = {
          workOrderId: `wo:${id}`, machineIndex: e.machine, componentIndex: e.component,
          technicianIndex: e.technician, kind: e.kind, status: 'IN_PROGRESS',
          startedTick: e.tick, completedTick: null, plannedDurationTicks: e.duration,
          remainingTicks: null, waitTicks: failure ? e.tick - failure.tick : null,
          startEventId: id, completionEventId: null, failureEventId: failure?.id ?? null,
          decisionTick: decision?.tick ?? null, assignmentSource,
        };
        // A new start consumes the component failure, never reuse it for another job.
        delete p.failures[component(e)];
      }
      if (e.type === 'completion') {
        const open = Object.values(p.orders).filter(o => o.status === 'IN_PROGRESS' &&
          tuple({ machine: o.machineIndex, component: o.componentIndex, technician: o.technicianIndex, kind: o.kind }) === tuple(e));
        if (open.length > 1) throw new Error('Ambiguous work-order completion');
        if (open.length) Object.assign(open[0], { status: 'COMPLETED', completedTick: e.tick, remainingTicks: 0, completionEventId: id });
        else p.historyCoverage = 'PARTIAL';
      }
    });
    p.processedThroughTick = record.tick + 1;
  }
  if (p.processedThroughTick !== tick) {
    if (previous) throw new Error('Work-order projection missing final interval');
    p.historyCoverage = 'PARTIAL';
    p.processedThroughTick = tick;
  }
  for (const order of Object.values(p.orders)) {
    if (order.status !== 'IN_PROGRESS') continue;
    const job = payload.primary.state.jobs[order.technicianIndex];
    order.remainingTicks = job && tuple(job) === tuple({ machine: order.machineIndex,
      component: order.componentIndex, technician: order.technicianIndex, kind: order.kind }) ? job.remaining : null;
  }
  return p;
}

function present(row, { machineIndex, limit = 20 } = {}) {
  const projection = row.workOrdersJson ?? project(row.id, row.payloadJson);
  const orders = Object.values(projection.orders).filter(o => machineIndex === undefined || o.machineIndex === machineIndex)
    .sort((a, b) => b.startedTick - a.startedTick || (a.startEventId < b.startEventId ? 1 : a.startEventId > b.startEventId ? -1 : 0));
  return { contractVersion: 'jcst-work-orders/v1', sessionId: row.id, revision: row.revision,
    tick: row.payloadJson.primary.state.tick, stepSeconds: row.payloadJson.step_seconds ?? 900,
    lane: 'primary', source: 'JCST_SIMULATION', historyCoverage: projection.historyCoverage,
    total: orders.length, items: orders.slice(0, limit) };
}
module.exports = { eventId, project, present };
