import { test, expect } from '@playwright/test';
import path from 'node:path';
test('real authenticated evidence import, reload, replay, branch, review and legacy navigation',async({page},testInfo)=>{
  await page.goto('/login');
  await page.getByLabel('Username').fill('jcst-browser');
  await page.getByLabel('Password',{exact:true}).fill('jcst-browser-test-password');
  await page.getByRole('button',{name:/sign in/i}).click();
  await page.goto('/research');
  await page.getByRole('link',{name:'JCST engineering verification',exact:true}).click();
  await expect(page.getByText('Local physical replay PASS · 1 included traces')).toBeVisible();
  await expect(page.getByText('Statistics: source reports only')).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('research-campaign.png'),fullPage:true});
  await page.reload();
  await page.getByRole('link',{name:/base \/ threshold5 · seed 990000001/}).click();
  await expect(page.getByRole('heading',{name:'Episode replay',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Step',exact:true}).click();
  await expect(page.getByText('Tick 1 · controlled horizon')).toBeVisible();
  await page.getByRole('button',{name:'Reset',exact:true}).click();
  await expect(page.getByText('Tick 0 · controlled horizon')).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('research-replay.png'),fullPage:true});
  await page.getByText('Create a simulation branch from tick 0').click();
  await page.getByRole('textbox',{name:'Reason',exact:true}).fill('Browser acceptance: preserve original episode and compare copied-state WAIT.');
  await page.getByRole('button',{name:'Run simulation branch',exact:true}).click();
  await page.getByRole('link',{name:/Follow branch/}).click();
  await expect(page.getByText('SUCCEEDED',{exact:true})).toBeVisible({timeout:20000});
  await page.getByText('Replay this simulation branch').click();
  await expect(page.getByRole('slider',{name:'Branch tick'})).toBeVisible();
  await page.getByRole('textbox',{name:'Review reason',exact:true}).fill('Accepted as simulation evidence only.');
  await page.getByRole('button',{name:'Accept simulation result',exact:true}).click();
  await expect(page.getByText('ACCEPT',{exact:true})).toBeVisible();
  await page.reload(); await expect(page.getByText('ACCEPT',{exact:true})).toBeVisible();
  await page.goto('/research/import');
  await page.getByLabel('Bundle JSON file').setInputFiles(path.resolve('../contracts/jcst/v1/fixtures/engineering-bundle.json'));
  await page.getByRole('button',{name:'Queue validated import'}).click();
  await page.getByRole('link',{name:'Follow job and validation'}).click();
  await expect(page.getByText('SUCCEEDED',{exact:true})).toBeVisible({timeout:20000});
  await page.getByRole('link',{name:'Open imported campaign →'}).click();
  await expect(page.getByRole('heading',{name:'JCST engineering verification',exact:true})).toBeVisible();
  await expect(page.getByRole('link',{name:'Legacy CNC experiments'})).toHaveCount(0);
  await page.goto('/experiments');
  await expect(page).toHaveURL(/\/experiments$/);
});

test('existing SE1 evidence renders actual learning curves and registered S/F/A inference',async({page},testInfo)=>{
  test.skip(!process.env.JCST_E2E_SE1_BUNDLE,'Existing SE1 artifacts are supplied explicitly; never generated in CI.');
  await page.goto('/login'); await page.getByLabel('Username').fill('jcst-browser');
  await page.getByLabel('Password',{exact:true}).fill('jcst-browser-test-password');
  await page.getByRole('button',{name:/sign in/i}).click();
  await page.goto('/research/import');
  await page.getByLabel('Bundle JSON file').setInputFiles(process.env.JCST_E2E_SE1_BUNDLE!);
  await page.getByRole('button',{name:'Queue validated import'}).click();
  await page.getByRole('link',{name:'Follow job and validation'}).click();
  await expect(page.getByText('SUCCEEDED',{exact:true})).toBeVisible({timeout:30000});
  await page.getByRole('link',{name:'Open imported campaign →'}).click();
  await expect(page.getByRole('img',{name:/Per-root samples learning curves/})).toBeVisible();
  await expect(page.getByText('Local physical replay PASS · 6 included traces')).toBeVisible();
  await expect(page.getByText('Per-root checkpoints (480)')).toBeVisible();
  await page.getByRole('combobox',{name:'Case',exact:true}).selectOption('generalist');
  await expect(page).toHaveURL(/case=generalist/);
  await page.getByRole('combobox',{name:'Arm',exact:true}).selectOption('A');
  await page.getByRole('combobox',{name:'Training root',exact:true}).selectOption('0');
  await page.getByRole('combobox',{name:'Show through decisions',exact:true}).selectOption('96000');
  await expect(page.getByText(/Curve filters select 4 checkpoint rows/)).toBeVisible();
  await page.reload();
  await expect(page.getByRole('combobox',{name:'Arm',exact:true})).toHaveValue('A');
  await expect(page.getByText(/Curve filters select 4 checkpoint rows/)).toBeVisible();
  await page.getByRole('combobox',{name:'Arm',exact:true}).selectOption('all');
  await page.getByRole('combobox',{name:'Training root',exact:true}).selectOption('all');
  await page.getByRole('combobox',{name:'Show through decisions',exact:true}).selectOption('all');
  await expect(page.getByText(/Curve filters select 240 checkpoint rows/)).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('se1-results-generalist.png'),fullPage:true});
  await page.getByRole('link',{name:/base \/ S · seed/}).first().click();
  if(process.env.JCST_RELEASE_REGISTRY){
    await page.getByRole('combobox',{name:'Registered checkpoint'}).selectOption('se1-base-S-root0-96k');
    await page.getByRole('button',{name:'Run greedy inference'}).click();
    await page.getByRole('link',{name:'Follow inference job →'}).click();
    await expect(page.getByText('SUCCEEDED',{exact:true})).toBeVisible({timeout:30000});
    await expect(page.getByText(/S · matching/)).toBeVisible();
  }
});
